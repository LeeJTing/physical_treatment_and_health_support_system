"""Builds supabase/seed/seed_food.sql from assets/seed/food_catalogue.json, the food catalogue the
AI server uses too (fyp-fastapi: training/food/build_catalogue.py writes it from USDA FoodData
Central ingredients, standard recipes and Malaysian laboratory analyses). Run after a change to the
catalogue, then run seed_food.sql in the SQL Editor (after the migrations up to
20261101120000_food_names_and_targets.sql). Re-running it updates the rows in place.

    python supabase/seed/build_food_seed.py

food_id is a UUID derived from food_key (uuid5), so the same food keeps the same id in every
project and in the app's fake repository. The "Foods I cannot eat" list (dietary_restriction, food
names such as Onion or Pork) and each food's food_restriction rows (the food names its recipe
contains) come from the same file.
"""
import json
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "assets" / "seed" / "food_catalogue.json"
OUT = Path(__file__).with_name("seed_food.sql")
NS = uuid.UUID("6f1c6c1e-3f0e-4a8a-9d55-7a7c3a9b2f10")


def food_id(key: str) -> str:
    return str(uuid.uuid5(NS, key))


def q(s) -> str:
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    ids = {e["restriction_code"]: e["restriction_id"] for e in data["exclusions"]}
    names = [f"  ({e['restriction_id']}, {q(e['restriction_code'])}, {q(e['restriction_name'])}, 'FOOD', "
             f"{q(e['food_group'])}, true)" for e in data["exclusions"]]
    rows, tags = [], []
    for f in data["foods"]:
        fid = food_id(f["food_key"])
        slots = "array[" + ",".join(q(s) for s in f["meal_slots"]) + "]::text[]" if f["meal_slots"] else "'{}'::text[]"
        rows.append(
            f"  ({q(fid)}, {q(f['food_key'])}, {q(f['food_name'])}, {q(f['food_category'])}, {f['base_serving_g']}, "
            f"{f['energy_kcal_per_100g']}, {f['carb_g_per_100g']}, {f['protein_g_per_100g']}, {f['fat_g_per_100g']}, "
            f"{f['sodium_mg_per_100g']}, {f['sugar_g_per_100g']}, {f['total_sugar_g_per_100g']}, "
            f"{f['sat_fat_g_per_100g']}, {f['fibre_g_per_100g']}, {f['potassium_mg_per_100g']}, "
            f"{f['phosphorus_mg_per_100g']}, {f['calcium_mg_per_100g']}, {f['caffeine_mg_per_100g']}, "
            f"{'true' if f['needs_two_hands'] else 'false'}, {q(f['two_hands_reason'])}, {q(f['pregnancy_caution'])}, "
            f"{q(f['data_source'])}, {q(f['plan_role'])}, {slots})")
        for t in f["restrictions"]:
            tags.append(f"  ({q(fid)}, {ids[t]})")
    sql = f"""-- Generated by supabase/seed/build_food_seed.py from assets/seed/food_catalogue.json
-- ({data['version']}, {data['count']} foods, {len(ids)} food names). Do not edit by hand.
begin;

insert into public.dietary_restriction
  (restriction_id, restriction_code, restriction_name, restriction_type, food_group, is_active) values
{",\n".join(names)}
on conflict (restriction_id) do update set
  restriction_code = excluded.restriction_code, restriction_name = excluded.restriction_name,
  restriction_type = excluded.restriction_type, food_group = excluded.food_group, is_active = true;

insert into public.food_item
  (food_id, food_key, food_name, food_category, base_serving_g, energy_kcal_per_100g, carb_g_per_100g,
   protein_g_per_100g, fat_g_per_100g, sodium_mg_per_100g, sugar_g_per_100g, total_sugar_g_per_100g,
   sat_fat_g_per_100g, fibre_g_per_100g, potassium_mg_per_100g, phosphorus_mg_per_100g, calcium_mg_per_100g,
   caffeine_mg_per_100g, needs_two_hands, two_hands_reason, pregnancy_caution, data_source, plan_role,
   meal_slots) values
{",\n".join(rows)}
on conflict (food_id) do update set
  food_key = excluded.food_key, food_name = excluded.food_name, food_category = excluded.food_category,
  base_serving_g = excluded.base_serving_g, energy_kcal_per_100g = excluded.energy_kcal_per_100g,
  carb_g_per_100g = excluded.carb_g_per_100g, protein_g_per_100g = excluded.protein_g_per_100g,
  fat_g_per_100g = excluded.fat_g_per_100g, sodium_mg_per_100g = excluded.sodium_mg_per_100g,
  sugar_g_per_100g = excluded.sugar_g_per_100g, total_sugar_g_per_100g = excluded.total_sugar_g_per_100g,
  sat_fat_g_per_100g = excluded.sat_fat_g_per_100g, fibre_g_per_100g = excluded.fibre_g_per_100g,
  potassium_mg_per_100g = excluded.potassium_mg_per_100g, phosphorus_mg_per_100g = excluded.phosphorus_mg_per_100g,
  calcium_mg_per_100g = excluded.calcium_mg_per_100g, caffeine_mg_per_100g = excluded.caffeine_mg_per_100g,
  needs_two_hands = excluded.needs_two_hands, two_hands_reason = excluded.two_hands_reason,
  pregnancy_caution = excluded.pregnancy_caution, data_source = excluded.data_source,
  plan_role = excluded.plan_role, meal_slots = excluded.meal_slots;

delete from public.food_restriction where food_id in (select food_id from public.food_item where food_key is not null);
insert into public.food_restriction (food_id, restriction_id) values
{",\n".join(tags)}
on conflict do nothing;

commit;
"""
    OUT.write_text(sql, encoding="utf-8")
    print(f"{data['count']} foods, {len(ids)} food names, {len(tags)} food_restriction rows -> {OUT}")


if __name__ == "__main__":
    main()
